/*
 * Port of shared/phone/types.ts — 📱 Phone practice (手机练习, docs/PHONE_PRACTICE.md): a task is
 * a SCENARIO SPEC (plain JSON, checked by [PhoneValidate]) holding the apps it uses, the seeded
 * world those apps render, the goal in English + Chinese, hints and declarative goal conditions
