/** Port of `BUNDLED_SCENARIOS` / `bundledScenario` (resources/phone/scenarios.json). */
object PhoneScenarios {
    val json = Json { ignoreUnknownKeys = true; explicitNulls = false }

    /** The raw JSON of each bundled scenario (what the validator checks). */
    val raw: List<JsonObject> by lazy {
        val text = PhoneScenarios::class.java.getResourceAsStream("/phone/scenarios.json")!!.bufferedReader(Charsets.UTF_8).readText()
        json.parseToJsonElement(text).jsonArray.map { it.jsonObject }
    }

    val all: List<ScenarioSpec> by lazy { raw.map(::decode) }

    fun decode(e: JsonElement): ScenarioSpec = json.decodeFromJsonElement(e)

    fun byId(id: String): ScenarioSpec? = all.firstOrNull { it.id == id }

    fun persona(spec: ScenarioSpec, id: String?): PhonePersona? = id?.let { pid -> spec.personas?.firstOrNull { it.id == pid } }
}
